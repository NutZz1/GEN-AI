"""Evaluation for the LLM agent layer (agent/). Writes results/metrics_agent.json and
results/failures.png. Companion to evaluate.py, which evaluates the VAE/trait model itself -
this script never touches or re-derives those numbers, only reads results/{model}/metrics.json for
context if it's already there.

1. Parser accuracy on knowledge/prompt_testset.jsonl's held-out `test` split (30 prompts), for the
   rule-based parser (text2avatar.py) and, if an LLM backend is configured, the LLM parser - with and
   without the validate-and-retry step (agent/schemas.py). Two things are scored per trait, because
   they answer different questions:
     - trait key precision/recall: did the parser notice the *right traits* were mentioned at all?
     - exact-match rate (on traits both gold and the parser agree were mentioned): did it name the
       *exact* variant-id set, not just the right trait?
   Gold labels for `easy`/`compositional`/`negation` prompts were generated by running
   text2avatar.parse() itself (see knowledge/build_prompt_testset.py) - the rule parser is EXPECTED to
   score ~100% there by construction. `code_mixed` and `vague` prompts are where an LLM parser (if
   configured) should show a real gap over the rule parser, which has no non-English/no-persona
   vocabulary at all.
2. Trait satisfaction rate, before vs. after the verify/self-correct loop: for every test prompt with
   at least one gold trait constraint, generate an avatar once (no retries) and again through
   generate_verified_candidate() (up to MAX_RETRIES), and check the independent judge classifier's
   opinion both times.
3. Latency and fallback rate (how often the LLM path was unavailable/failed and the rule-based /
   heuristic path ran instead).
4. Frechet distance (same judge-classifier-feature metric evaluate.py uses) between the avatars this
   script generated from test prompts and real held-out avatars, for an FID-style realism number -
   feasible on CPU/MPS since it reuses the already-trained judge classifier, no new network needed.
5. A failure-case gallery (results/failures.png) of every prompt that still didn't verify after
   self-correction, with the missed trait(s) captioned - or a note if there were none in this run.

    python evaluate_agent.py
"""
import json
import time

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch

from agent import config as agent_config
from agent import llm as agent_llm
from agent.agent import ParseResult, generate_verified_candidate, parse_request, verify_avatar
from agent.schemas import validate_parser_json
from agent.tools import AgentContext, compute_residual_pool
from agent.prompts import PARSER_PROMPT_V1
from avatarblend import ROOT, default_ckpt, describe_device, get_device, load_dataset, load_model, to_tensor
from evaluate import AttrClassifier, TRAITS as JUDGE_TRAITS, frechet, judge_features
from traits import TRAITS as TRAIT_NAMES, TraitSpace, build, traits_path
import text2avatar as t2a

OUT = ROOT / "results"
TESTSET = ROOT / "knowledge" / "prompt_testset.jsonl"
DEVICE = get_device()


def load_testset(split="test"):
    items = [json.loads(line) for line in TESTSET.read_text().splitlines() if line.strip()]
    return [it for it in items if it["split"] == split]


def score_item(predicted, gold):
    """-> (precision, recall, exact_match) for one item. See module docstring for definitions."""
    gold_traits = {t for t in gold if t in TRAIT_NAMES and gold[t]}
    pred_traits = {t for t, ids in predicted.items() if ids}
    tp = len(gold_traits & pred_traits)
    precision = (tp / len(pred_traits)) if pred_traits else (1.0 if not gold_traits else 0.0)
    recall = (tp / len(gold_traits)) if gold_traits else (1.0 if not pred_traits else 0.0)
    if gold_traits:
        matches = [set(predicted.get(t, [])) == set(gold[t]) for t in gold_traits]
        exact = sum(matches) / len(gold_traits)
    else:
        exact = 1.0 if not pred_traits else 0.0
    return precision, recall, exact


def parser_eval(items, parse_fn, label):
    rows, by_cat, latencies, fallbacks = [], {}, [], 0
    for item in items:
        t0 = time.time()
        predicted, source = parse_fn(item["prompt"])
        latencies.append(time.time() - t0)
        if source != "llm":
            fallbacks += 1
        p, r, e = score_item(predicted, item["gold"])
        rows.append({"id": item["id"], "category": item["category"], "precision": p, "recall": r, "exact": e,
                    "source": source})
        by_cat.setdefault(item["category"], []).append((p, r, e))
    agg = lambda vals: {"precision": float(np.mean([v[0] for v in vals])),
                        "recall": float(np.mean([v[1] for v in vals])),
                        "exact_match": float(np.mean([v[2] for v in vals]))}
    return {"label": label, "overall": agg([(r["precision"], r["recall"], r["exact"]) for r in rows]),
            "by_category": {c: agg(v) for c, v in by_cat.items()},
            "mean_latency_s": float(np.mean(latencies)), "fallback_rate": fallbacks / len(items), "n": len(items)}


def rule_parse_fn(prompt):
    cons, _, _ = t2a.parse(prompt)
    return cons, "rule"


def make_llm_parse_fn(llm, use_retry_validation):
    def fn(prompt):
        if not llm.available:
            cons, _, _ = t2a.parse(prompt)
            return cons, "rule_fallback"
        if use_retry_validation:
            result = parse_request(llm, prompt)  # includes the pydantic validate + one re-ask + fallback
            return result.constraints, result.source
        # LLM parser with NO validation/retry - a single raw call, to isolate what validation buys us
        resp = llm.chat(system=PARSER_PROMPT_V1, messages=[{"role": "user", "content": prompt}], json_mode=True)
        if resp.error:
            cons, _, _ = t2a.parse(prompt)
            return cons, "rule_fallback"
        parsed, err = validate_parser_json(resp.text)
        if parsed is None:
            cons, _, _ = t2a.parse(prompt)
            return cons, "rule_fallback"
        return parsed.constraints(), "llm"
    return fn


def trait_satisfaction_eval(ctx, items, residual_strength=0.7):
    before, after, retries_list, failures = [], [], [], []
    for item in items:
        gold = {t: ids for t, ids in item["gold"].items() if t in TRAIT_NAMES and ids}
        if not gold:
            continue
        from agent.tools import generate_from_constraints
        r0 = generate_from_constraints(ctx, gold, residual_strength, name=f"eval_{item['id']}_try0")
        v0 = verify_avatar(ctx, r0["avatar"], gold)
        hit0 = all(v["hit"] for v in v0.values()) if v0 else None

        parse = ParseResult(constraints=gold, understood=[], unknown=[], source="gold")
        cand = generate_verified_candidate(ctx, parse, residual_strength, name=f"eval_{item['id']}_final")
        v1 = cand["verify"]
        hit1 = all(v["hit"] for v in v1.values()) if v1 else None

        if hit0 is not None:
            before.append(hit0)
        if hit1 is not None:
            after.append(hit1)
        retries_list.append(cand["retries"])
        if hit1 is False:
            missed = [LABEL for LABEL, v in v1.items() if not v["hit"]]
            failures.append({"id": item["id"], "prompt": item["prompt"], "img": cand["img"], "missed": missed})
    return {"before_self_correct": float(np.mean(before)) if before else None,
            "after_self_correct": float(np.mean(after)) if after else None,
            "mean_retries": float(np.mean(retries_list)) if retries_list else None,
            "n_scored": len(after)}, failures


def failure_gallery(failures, path):
    if not failures:
        return False
    n = len(failures)
    cols = min(n, 6)
    rows = (n + cols - 1) // cols
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 1.8, rows * 2.0))
    axes = np.atleast_2d(axes).flatten()
    for ax, f in zip(axes, failures):
        ax.imshow(f["img"])
        ax.set_title(f"{f['id']}\nmissed: {', '.join(f['missed'])}", fontsize=6)
        ax.set_xticks([]), ax.set_yticks([])
    for ax in axes[len(failures):]:
        ax.axis("off")
    plt.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)
    return True


@torch.no_grad()
def agent_realism(ctx, model, data, items):
    """Frechet distance between judge-classifier features of test-prompt-generated avatars and real
    held-out avatars - same metric evaluate.py uses for the VAE itself, applied to what the agent
    actually produces end-to-end."""
    clf_path = ROOT / "checkpoints" / "attr_classifier.pt"
    if not clf_path.exists():
        return None
    names = list(data["attr_names"])
    n_classes = [int(data["attr_nvariants"][names.index(t)]) for t in JUDGE_TRAITS]
    clf = AttrClassifier(n_classes).to(DEVICE)
    clf.load_state_dict(torch.load(clf_path, map_location=DEVICE))
    clf.eval()
    te = np.nonzero(data["split"] == 2)[0][:1000]
    f_real = judge_features(clf, to_tensor(data["images"][te]).to(DEVICE))
    agent_imgs = np.stack([a["img"] for name, a in ctx.avatars.items() if name.startswith("eval_")])
    if len(agent_imgs) == 0:
        return None
    f_agent = judge_features(clf, to_tensor(agent_imgs).to(DEVICE))
    return {"fid_style_agent_vs_real": frechet(f_agent, f_real), "n_real": int(len(te)), "n_agent": int(len(agent_imgs))}


def main():
    ckpt = default_ckpt()
    model = load_model(ckpt, device=DEVICE)
    print(f"device: {describe_device(DEVICE)}  model: {ckpt.name}")
    data = load_dataset(model.img_size)
    from avatarblend import encode_mu
    if traits_path(model).exists():
        traits, mu = TraitSpace.load(traits_path(model)), encode_mu(model, data["images"])
    else:
        traits, mu = build(model, data)
    pool = compute_residual_pool(traits, mu, data)

    test_items = load_testset("test")
    print(f"{len(test_items)} test prompts")

    llm = agent_llm.get_client()
    print(f"LLM backend: {llm.name} (available={llm.available})")

    parser_results = {"rule_based": parser_eval(test_items, rule_parse_fn, "rule_based")}
    if llm.available:
        parser_results["llm_no_validation"] = parser_eval(test_items, make_llm_parse_fn(llm, False), "llm_no_validation")
        parser_results["llm_with_validation_retry"] = parser_eval(test_items, make_llm_parse_fn(llm, True),
                                                                   "llm_with_validation_retry")
    else:
        parser_results["llm_note"] = ("no LLM backend configured (ANTHROPIC_API_KEY unset) - only the "
                                      "rule-based parser ran in this evaluation. Set the key and re-run "
                                      "for the LLM-vs-rule comparison.")

    ctx = AgentContext(model, traits, pool, rng=np.random.default_rng(0))
    satisfaction, failures = trait_satisfaction_eval(ctx, test_items)
    failure_gallery(failures, OUT / "failures.png")
    realism = agent_realism(ctx, model, data, test_items)

    metrics = {"model": ckpt.name, "llm_backend": llm.name, "llm_available": llm.available,
              "max_retries": agent_config.MAX_RETRIES, "n_test_prompts": len(test_items),
              "parser_accuracy": parser_results, "trait_satisfaction": satisfaction,
              "n_failures_after_self_correct": len(failures), "agent_realism_vs_real": realism}
    (OUT / "metrics_agent.json").write_text(json.dumps(metrics, indent=1))
    print(json.dumps(metrics, indent=1))


if __name__ == "__main__":
    main()
